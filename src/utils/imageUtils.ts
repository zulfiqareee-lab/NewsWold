// Returns a verified, working image URL for any category
export function getCategoryDefaultImage(categorySlug: string = 'international-news', seed = 0): string {
  const images = CATEGORY_IMAGE_MAP[categorySlug] || CATEGORY_IMAGE_MAP['international-news'];
  const index = Math.abs(seed) % images.length;
  return images[index] || images[0];
}

// Clean and sanitize any image URL:
// 1. If it has broken path like /src/assets/images/..., replace with /images/...
// 2. If it is empty or invalid, return category default image
export function sanitizeImageUrl(rawUrl?: string, categorySlug: string = 'international-news'): string {
  if (!rawUrl || rawUrl.trim() === '') {
    return getCategoryDefaultImage(categorySlug);
  }

  const clean = rawUrl.trim();

  // Fix path mistake: /src/assets/images/ -> /images/
  if (clean.startsWith('/src/assets/images/')) {
    return clean.replace('/src/assets/images/', '/images/');
  }

  // If starts with /images/ or http, keep it
  if (clean.startsWith('/images/') || clean.startsWith('http://') || clean.startsWith('https://') || clean.startsWith('data:')) {
    return clean;
  }

  return getCategoryDefaultImage(categorySlug);
}
